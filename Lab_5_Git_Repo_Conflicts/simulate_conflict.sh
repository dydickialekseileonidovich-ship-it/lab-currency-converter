#!/usr/bin/env bash
set -e

echo "=== Инициализация учебного репозитория Git ==="
rm -rf repo_demo
mkdir repo_demo
cd repo_demo

git init
git config user.name "Aleksey Duditskiy"
git config user.email "duditskiy@example.com"

cat << 'EOF' > price.md
# Прайс-лист студенческой мини-типографии

1. Ч/Б печать А4: 0.20 BYN / стр.
2. Цветная печать А4: 0.80 BYN / стр.
3. Твёрдый переплёт диплома: 18.00 BYN / шт.
4. Ламинирование А4: 1.50 BYN / шт.
5. Сканирование документов: 0.15 BYN / стр.
EOF

git add price.md
git commit -m "feat: начальный прейскурант типографии"

# Ветка 1: скидочные цены
git branch promo-discount
# Ветка 2: новые услуги
git branch new-services

echo "=== Внесение изменений в ветку promo-discount ==="
git checkout promo-discount
cat << 'EOF' > price.md
# Прайс-лист студенческой мини-типографии

1. Ч/Б печать А4 (акция для студентов): 0.15 BYN / стр.
2. Цветная печать А4 (акция): 0.60 BYN / стр.
3. Твёрдый переплёт диплома (сезонная скидка): 15.00 BYN / шт.
4. Ламинирование А4: 1.50 BYN / шт.
5. Сканирование документов: 0.15 BYN / стр.
EOF
git add price.md
git commit -m "promo: скидочные цены к сессии"

echo "=== Внесение конфликтующих изменений в ветку new-services ==="
git checkout new-services
cat << 'EOF' > price.md
# Прайс-лист студенческой мини-типографии

1. Ч/Б печать А4: 0.25 BYN / стр.
2. Цветная печать А4: 0.90 BYN / стр.
3. Печать чертежей А1: 4.50 BYN / шт.
4. Твёрдый переплёт диплома (с тиснением): 22.00 BYN / шт.
5. Ламинирование А4: 1.50 BYN / шт.
6. Сканирование документов: 0.15 BYN / стр.
7. Брошюровка на пружину: 3.00 BYN / шт.
EOF
git add price.md
git commit -m "feat: добавление чертежей А1 и пружинного переплёта, пересмотр базовых цен"

echo "=== Слияние веток и возникновение merge-конфликта ==="
git checkout main
git merge promo-discount

echo "Попытка слить new-services (ожидается конфликт)..."
set +e
git merge new-services
set -e

echo "=== Разрешение конфликта ==="
cat << 'EOF' > price.md
# Прайс-лист студенческой мини-типографии

1. Ч/Б печать А4 (акция для студентов): 0.15 BYN / стр.
2. Цветная печать А4 (акция): 0.60 BYN / стр.
3. Печать чертежей А1: 4.50 BYN / шт.
4. Твёрдый переплёт диплома (сезонная скидка): 15.00 BYN / шт.
5. Твёрдый переплёт с золотым тиснением: 22.00 BYN / шт.
6. Ламинирование А4: 1.50 BYN / шт.
7. Сканирование документов: 0.15 BYN / стр.
8. Брошюровка на пластиковую пружину: 3.00 BYN / шт.
EOF

git add price.md
git commit -m "merge: объединение новых услуг с сохранением студенческих промо-скидок"

echo "=== Слияние успешно завершено! История коммитов: ==="
git log --oneline --graph --all
